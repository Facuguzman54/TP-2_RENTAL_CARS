
CREATE TABLE CLIENTES(
    ID INT PRIMARY KEY,
    NOMBRE VARCHAR(50) NOT NULL,
    EMAIL VARCHAR(50) NOT NULL UNIQUE,
    TELEFONO VARCHAR(15) NOT NULL,
    CIUDAD VARCHAR(50) NOT NULL,
    FECHA_REGISTRO DATE NOT NULL,
    LICENCIA_CONDUCIR VARCHAR(20) NOT NULL
);

CREATE TABLE CATEGORIAS(
    ID INT PRIMARY KEY,
    NOMBRE VARCHAR(50) NOT NULL UNIQUE,
    DESCRIPCION VARCHAR(120) NOT NULL
);

CREATE TABLE SUCURSALES(
    ID INT PRIMARY KEY,
    NOMBRE VARCHAR(80) NOT NULL UNIQUE,
    DIRECCION VARCHAR(120) NOT NULL,
    CIUDAD VARCHAR(50) NOT NULL,
    TELEFONO VARCHAR(15) NOT NULL
);

CREATE TABLE VEHICULOS(
    ID INT PRIMARY KEY,
    MARCA VARCHAR(50) NOT NULL,
    MODELO VARCHAR(50) NOT NULL,
    ANIO INT NOT NULL,
    PRECIO_DIA DECIMAL(9, 2) NOT NULL,
    ESTADO INT NOT NULL DEFAULT 1,
    CATEGORIA_ID INT NOT NULL,
    SUCURSAL_ID INT NOT NULL,
    PATENTE VARCHAR(15) NOT NULL UNIQUE,
    KM_ACTUAL INT NOT NULL,
    FOREIGN KEY (CATEGORIA_ID) REFERENCES CATEGORIAS(ID),
    FOREIGN KEY (SUCURSAL_ID) REFERENCES SUCURSALES(ID)
);

CREATE TABLE EMPLEADOS(
    ID INT PRIMARY KEY,
    NOMBRE VARCHAR(80) NOT NULL,
    CARGO VARCHAR(50) NOT NULL,
    SUCURSAL_ID INT NOT NULL,
    FECHA_INGRESO DATE NOT NULL,
    SALARIO DECIMAL(10, 2) NOT NULL,
    FOREIGN KEY (SUCURSAL_ID) REFERENCES SUCURSALES(ID)
);

CREATE TABLE RESERVAS(
    ID INT PRIMARY KEY,
    ID_CLIENTE INT NOT NULL,
    ID_VEHICULO INT NOT NULL,
    FECHA_RESERVA DATE NOT NULL,
    FECHA_INICIO DATE NOT NULL,
    FECHA_FIN DATE NOT NULL,
    ESTADO VARCHAR(20) NOT NULL,
    FOREIGN KEY (ID_CLIENTE) REFERENCES CLIENTES(ID),
    FOREIGN KEY (ID_VEHICULO) REFERENCES VEHICULOS(ID)
);

CREATE TABLE MANTENIMIENTOS(
    ID INT PRIMARY KEY,
    ID_VEHICULO INT NOT NULL,
    FECHA DATE NOT NULL,
    TIPO VARCHAR(50) NOT NULL,
    COSTO DECIMAL(9, 2) NOT NULL,
    OBSERVACIONES VARCHAR(200) NOT NULL,
    FOREIGN KEY (ID_VEHICULO) REFERENCES VEHICULOS(ID)
);

CREATE TABLE ALQUILERES(
    ID_ALQUILER INT PRIMARY KEY,
    ID_CLIENTE INT NOT NULL,
    ID_VEHICULO INT NOT NULL,
    FECHA_INICIO DATE NOT NULL,
    FECHA_FIN DATE NOT NULL,
    TOTAL DECIMAL(9, 2) NOT NULL,
    ID_EMPLEADO INT NOT NULL,
    ID_SUCURSAL_RETIRO INT NOT NULL,
    ID_SUCURSAL_DEVOLUCION INT NOT NULL,
    ESTADO VARCHAR(20) NOT NULL,
    FOREIGN KEY (ID_CLIENTE) REFERENCES CLIENTES(ID),
    FOREIGN KEY (ID_VEHICULO) REFERENCES VEHICULOS(ID),
    FOREIGN KEY (ID_EMPLEADO) REFERENCES EMPLEADOS(ID),
    FOREIGN KEY (ID_SUCURSAL_RETIRO) REFERENCES SUCURSALES(ID),
    FOREIGN KEY (ID_SUCURSAL_DEVOLUCION) REFERENCES SUCURSALES(ID)
);

CREATE TABLE CHECK_ALQUILER(
    ID INT PRIMARY KEY,
    ID_ALQUILER INT NOT NULL,
    TIPO VARCHAR(20) NOT NULL,
    FECHA DATE NOT NULL,
    KM INT NOT NULL,
    NIVEL_COMBUSTIBLE INT NOT NULL,
    FOREIGN KEY (ID_ALQUILER) REFERENCES ALQUILERES(ID_ALQUILER)
);

CREATE TABLE SEGUROS(
    ID INT PRIMARY KEY,
    ID_ALQUILER INT NOT NULL,
    COMPANIA VARCHAR(80) NOT NULL,
    NUMERO_POLIZA VARCHAR(50) NOT NULL,
    COBERTURA VARCHAR(100) NOT NULL,
    COSTO DECIMAL(9, 2) NOT NULL,
    FOREIGN KEY (ID_ALQUILER) REFERENCES ALQUILERES(ID_ALQUILER)
);

CREATE TABLE PAGOS(
    ID INT PRIMARY KEY,
    ID_ALQUILER INT NOT NULL,
    FECHA_PAGO DATE NOT NULL,
    MONTO DECIMAL(9, 2) NOT NULL,
    FOREIGN KEY (ID_ALQUILER) REFERENCES ALQUILERES(ID_ALQUILER)
);

CREATE TABLE MULTAS(
    ID INT PRIMARY KEY,
    ID_ALQUILER INT NOT NULL,
    FECHA DATE NOT NULL,
    MOTIVO VARCHAR(120) NOT NULL,
    MONTO DECIMAL(9, 2) NOT NULL,
    PAGADA INT NOT NULL DEFAULT 0,
    FOREIGN KEY (ID_ALQUILER) REFERENCES ALQUILERES(ID_ALQUILER)
);

CREATE TABLE AUDITORIA_ALQUILERES(
    ID_AUDITORIA INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ID_ALQUILER INT NOT NULL,
    ID_CLIENTE INT NOT NULL,
    ID_VEHICULO INT NOT NULL,
    FECHA_REGISTRO TIMESTAMP NOT NULL,
    ACCION VARCHAR(50) NOT NULL,
    FOREIGN KEY (ID_ALQUILER) REFERENCES ALQUILERES(ID_ALQUILER),
    FOREIGN KEY (ID_CLIENTE) REFERENCES CLIENTES(ID),
    FOREIGN KEY (ID_VEHICULO) REFERENCES VEHICULOS(ID)
);